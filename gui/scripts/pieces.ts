// Bakes the cburnett piece SVGs into src/pieces.ts as data URIs, so the board
// needs no extra requests and no piece pops in late.
//
// Usage: npm run pieces   (only after changing the files in pieces/<set>/)

import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SET = "cburnett";
const root = fileURLToPath(new URL("..", import.meta.url));
const dir = `${root}pieces/${SET}`;

const files = (await readdir(dir)).filter((name) => name.endsWith(".svg")).sort();
const entries: string[] = [];
for (const file of files) {
  const svg = await readFile(`${dir}/${file}`);
  entries.push(`  ${file.replace(".svg", "")}: "data:image/svg+xml;base64,${svg.toString("base64")}",`);
}

const source = `// Generated by scripts/pieces.ts — do not edit by hand; run \`npm run pieces\`.
//
// The ${SET} piece set by Colin M.L. Burnett, GPLv2+. See pieces/README.md.

export type PieceKey = \`\${"w" | "b"}\${"K" | "Q" | "R" | "B" | "N" | "P"}\`;

export const PIECE_SVG: Record<PieceKey, string> = {
${entries.join("\n")}
};

/** chess.js gives a lower-case type; the files are named wK, bQ and so on. */
export const pieceUrl = (color: string, type: string): string =>
  PIECE_SVG[(color + type.toUpperCase()) as PieceKey];
`;
await writeFile(`${root}src/pieces.ts`, source);
console.log(`wrote src/pieces.ts: ${files.length} ${SET} pieces (${source.length} bytes)`);
